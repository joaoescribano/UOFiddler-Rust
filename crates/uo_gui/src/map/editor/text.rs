//! The English texts of the map editor, by key (`t("map.stamp")`), with `{0}`-style
//! placeholders filled by `tf`.

pub fn t(key: &str) -> &'static str {
    TEXTS
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, v)| *v)
        .unwrap_or_else(|| missing(key))
}

/// A key without text is a bug of the caller; it shows as is (kept once, not every frame).
fn missing(key: &str) -> &'static str {
    use std::collections::HashSet;
    use std::sync::Mutex;
    static SEEN: Mutex<Option<HashSet<&'static str>>> = Mutex::new(None);
    let mut seen = SEEN.lock().unwrap();
    let seen = seen.get_or_insert_with(HashSet::new);
    if let Some(known) = seen.get(key) {
        return known;
    }
    let leaked: &'static str = Box::leak(key.to_string().into_boxed_str());
    seen.insert(leaked);
    leaked
}

pub fn tf(key: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = t(key).to_string();
    for (i, arg) in args.iter().enumerate() {
        out = out.replace(&format!("{{{i}}}"), &arg.to_string());
    }
    out
}

